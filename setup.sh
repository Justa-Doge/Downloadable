#!/usr/bin/env bash
set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$PROJECT_DIR"

command -v python3 >/dev/null 2>&1 || { echo "Python 3 is required."; exit 1; }
command -v ffmpeg >/dev/null 2>&1 || {
  echo "FFmpeg is required. Install it with your distribution package manager, then run setup.sh again."
  echo "Ubuntu/Debian: sudo apt install ffmpeg"
  exit 1
}

python3 -m venv .venv
.venv/bin/python -m pip install --upgrade pip yt-dlp mutagen curl-cffi

if [[ -s .helper-token ]]; then
  IFS= read -r TOKEN < .helper-token
else
  TOKEN=$(.venv/bin/python -c 'import secrets; print(secrets.token_urlsafe(32))')
  printf '%s\n' "$TOKEN" > .helper-token
fi
chmod 600 .helper-token

if [[ -d /mnt/chromeos/MyFiles ]]; then
  HELPER_URL="http://penguin.linux.test:47821"
  HELPER_HOST="0.0.0.0"
  echo "ChromeOS Linux container detected. The extension will use penguin.linux.test."
else
  HELPER_URL="http://127.0.0.1:47821"
  HELPER_HOST="127.0.0.1"
fi
printf '// Generated by setup.sh.\nglobalThis.HELPER_TOKEN = "%s";\nglobalThis.HELPER_URL = "%s";\n' "$TOKEN" "$HELPER_URL" > extension/config.js

if command -v systemctl >/dev/null 2>&1 && systemctl --user show-environment >/dev/null 2>&1; then
  mkdir -p "$HOME/.config/systemd/user"
  cat > "$HOME/.config/systemd/user/downloadable-helper.service" <<EOF
[Unit]
Description=Downloadable local helper
After=network-online.target

[Service]
Type=simple
WorkingDirectory=$PROJECT_DIR
Environment=DOWNLOADABLE_HOST=$HELPER_HOST
ExecStart=$PROJECT_DIR/.venv/bin/python $PROJECT_DIR/helper/helper.py
Restart=on-failure
RestartSec=3

[Install]
WantedBy=default.target
EOF
  systemctl --user daemon-reload
  systemctl --user enable --now downloadable-helper.service
  echo "Downloadable helper installed as a user service."
else
  mkdir -p "$HOME/.local/state/downloadable"
  nohup env DOWNLOADABLE_HOST="$HELPER_HOST" "$PROJECT_DIR/.venv/bin/python" "$PROJECT_DIR/helper/helper.py" > "$HOME/.local/state/downloadable/helper.log" 2>&1 &
  echo $! > "$HOME/.local/state/downloadable/helper.pid"
  echo "Downloadable helper started for this session. Run start.sh again after reboot."
fi

echo
echo "Setup complete. Load this folder in Chrome's chrome://extensions page:"
echo "$PROJECT_DIR/extension"
